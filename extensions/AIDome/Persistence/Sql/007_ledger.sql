-- ── Commitments: structured promises with her response and the stakes ──
CREATE TABLE aidomme_commitments (
  "Id" uuid PRIMARY KEY,
  "UserId" integer NOT NULL REFERENCES users("Id") ON DELETE CASCADE,
  "Status" varchar(16) NOT NULL CHECK ("Status" IN ('Pending', 'Active', 'Kept', 'Broken', 'Declined')),
  "Scope" varchar(16) NOT NULL CHECK ("Scope" IN ('Session', 'Days')),
  "Days" integer NOT NULL DEFAULT 0,
  "NoOrgasm" boolean NOT NULL DEFAULT FALSE,
  "Long" boolean NOT NULL DEFAULT FALSE,
  "Intense" boolean NOT NULL DEFAULT FALSE,
  "Torturous" boolean NOT NULL DEFAULT FALSE,
  "Mean" boolean NOT NULL DEFAULT FALSE,
  "Teasing" boolean NOT NULL DEFAULT FALSE,
  "Note" varchar(500),
  "Stakes" text NOT NULL,
  "Response" varchar(1000) NOT NULL,
  "Countered" boolean NOT NULL DEFAULT FALSE,
  "Proposed" text,
  "CreatedAtUtc" timestamptz NOT NULL,
  "AcceptedAtUtc" timestamptz,
  "StartsAtUtc" timestamptz,
  "EndsAtUtc" timestamptz,
  "SessionId" integer REFERENCES aidomme_sessions("Id") ON DELETE SET NULL,
  "ResolvedAtUtc" timestamptz,
  "Resolution" varchar(1000));
CREATE INDEX "IX_aidomme_commitments_UserId_Status" ON aidomme_commitments ("UserId", "Status");

-- ── Offers she made during sessions, with the parameters as filled in ──
CREATE TABLE aidomme_offers (
  "Id" uuid PRIMARY KEY,
  "UserId" integer NOT NULL REFERENCES users("Id") ON DELETE CASCADE,
  "DefinitionId" integer REFERENCES aidomme_offer_definitions("Id") ON DELETE SET NULL,
  "SessionId" integer REFERENCES aidomme_sessions("Id") ON DELETE SET NULL,
  "Buys" varchar(16) NOT NULL CHECK ("Buys" IN ('Orgasm', 'Rest', 'Mercy')),
  "Kind" varchar(32) NOT NULL,
  "Amount" integer NOT NULL,
  "Hold" integer NOT NULL DEFAULT 0,
  "Severity" integer NOT NULL,
  "Points" double precision NOT NULL,
  "Flavor" varchar(16) NOT NULL,
  "Text" varchar(1000) NOT NULL,
  "Status" varchar(16) NOT NULL CHECK ("Status" IN ('Proposed', 'Accepted', 'Declined', 'Expired')),
  "CreatedAtUtc" timestamptz NOT NULL,
  "DecidedAtUtc" timestamptz);
CREATE INDEX "IX_aidomme_offers_UserId_CreatedAtUtc" ON aidomme_offers ("UserId", "CreatedAtUtc");

-- ── Questions she asks before anything else ──
CREATE TABLE aidomme_followups (
  "Id" uuid PRIMARY KEY,
  "UserId" integer NOT NULL REFERENCES users("Id") ON DELETE CASCADE,
  "Kind" varchar(32) NOT NULL CHECK ("Kind" IN ('UnauthorizedOrgasm', 'InterruptedSession')),
  "Status" varchar(16) NOT NULL CHECK ("Status" IN ('Open', 'Answered', 'Voided')),
  "SessionId" integer REFERENCES aidomme_sessions("Id") ON DELETE SET NULL,
  "EventId" uuid REFERENCES aidomme_tracker_events("Id") ON DELETE SET NULL,
  "OccurredAtUtc" timestamptz NOT NULL,
  "Commitments" text NOT NULL,
  "DuringDenial" boolean NOT NULL DEFAULT FALSE,
  "Observed" varchar(1000) NOT NULL,
  "CreatedAtUtc" timestamptz NOT NULL,
  "Answer" varchar(32),
  "AnsweredAtUtc" timestamptz);
CREATE UNIQUE INDEX "IX_aidomme_followups_EventId" ON aidomme_followups ("EventId") WHERE "EventId" IS NOT NULL;
CREATE INDEX "IX_aidomme_followups_UserId_Status" ON aidomme_followups ("UserId", "Status");

-- ── The punishment ledger ──
CREATE TABLE aidomme_ledger (
  "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "UserId" integer NOT NULL REFERENCES users("Id") ON DELETE CASCADE,
  "Kind" varchar(32) NOT NULL CHECK ("Kind" IN ('Denial', 'PunishmentSession', 'PunishmentEnding', 'Edges', 'Ruin')),
  "Amount" integer NOT NULL CHECK ("Amount" > 0),
  "Remaining" integer NOT NULL CHECK ("Remaining" >= 0),
  "Severity" integer NOT NULL CHECK ("Severity" BETWEEN 1 AND 10),
  "Origin" varchar(16) NOT NULL CHECK ("Origin" IN ('Rule', 'Commitment', 'Offer', 'Legacy')),
  "Reason" varchar(1000) NOT NULL,
  "SessionId" integer REFERENCES aidomme_sessions("Id") ON DELETE SET NULL,
  "CommitmentId" uuid REFERENCES aidomme_commitments("Id") ON DELETE SET NULL,
  "OfferId" uuid REFERENCES aidomme_offers("Id") ON DELETE SET NULL,
  "FollowUpId" uuid REFERENCES aidomme_followups("Id") ON DELETE SET NULL,
  "CreatedAtUtc" timestamptz NOT NULL,
  "StartsAtUtc" timestamptz,
  "EndsAtUtc" timestamptz,
  "Status" varchar(16) NOT NULL CHECK ("Status" IN ('Owed', 'Serving', 'Served')),
  "ServingSessionId" integer REFERENCES aidomme_sessions("Id") ON DELETE SET NULL,
  "ServedAtUtc" timestamptz);
CREATE INDEX "IX_aidomme_ledger_UserId_Status" ON aidomme_ledger ("UserId", "Status");

-- Earlier punishments: denial periods keep their window; everything else is an owed punishment session.
INSERT INTO aidomme_ledger ("UserId", "Kind", "Amount", "Remaining", "Severity", "Origin", "Reason", "SessionId",
    "CreatedAtUtc", "StartsAtUtc", "EndsAtUtc", "Status", "ServedAtUtc")
  SELECT p."UserId",
    CASE WHEN p."Category" = 0 AND p."DenialEndsAtUtc" IS NOT NULL THEN 'Denial' ELSE 'PunishmentSession' END,
    CASE WHEN p."Category" = 0 AND p."DenialEndsAtUtc" IS NOT NULL
      THEN GREATEST(1, CEIL(EXTRACT(EPOCH FROM (p."DenialEndsAtUtc" - p."IssuedAtUtc")) / 86400)::integer)
      ELSE GREATEST(1, p."RemainingCount") END,
    CASE WHEN p."Completed" THEN 0
      WHEN p."Category" = 0 AND p."DenialEndsAtUtc" IS NOT NULL
        THEN GREATEST(1, CEIL(EXTRACT(EPOCH FROM (p."DenialEndsAtUtc" - p."IssuedAtUtc")) / 86400)::integer)
      ELSE GREATEST(1, p."RemainingCount") END,
    LEAST(10, GREATEST(1, p."Tier")), 'Legacy', LEFT(COALESCE(NULLIF(p."Description", ''), 'Punishment from an earlier version'), 1000),
    p."SessionId", p."IssuedAtUtc",
    CASE WHEN p."Category" = 0 THEN p."IssuedAtUtc" END,
    CASE WHEN p."Category" = 0 THEN p."DenialEndsAtUtc" END,
    CASE WHEN p."Completed" OR (p."Category" = 0 AND p."DenialEndsAtUtc" <= now()) THEN 'Served' ELSE 'Owed' END,
    CASE WHEN p."Completed" THEN COALESCE(p."CompletedAtUtc", p."IssuedAtUtc")
      WHEN p."Category" = 0 AND p."DenialEndsAtUtc" <= now() THEN p."DenialEndsAtUtc" END
  FROM aidomme_punishments p;

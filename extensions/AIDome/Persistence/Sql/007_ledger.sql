-- 007_ledger: structured commitments, the offer library, follow-up questions and the punishment ledger.
--
-- Replaces the free-form offer/commitment tables from 005 and the punishment table. Earlier offers,
-- commitments and reports had no structure the domme can enforce: if an install has any, they are
-- kept under aidomme_legacy_* names; otherwise the tables are dropped. Earlier punishments become
-- ledger entries with origin 'Legacy'.

-- ── Earlier free-form commitments ──
DO $legacy$
DECLARE
  item record;
BEGIN
  IF EXISTS (SELECT 1 FROM aidomme_offers) OR EXISTS (SELECT 1 FROM aidomme_commitments)
     OR EXISTS (SELECT 1 FROM aidomme_commitment_reports) THEN
    -- Their indexes and keys move with them, so the new tables can use the usual names.
    FOR item IN SELECT indexname FROM pg_indexes WHERE schemaname = current_schema()
        AND tablename IN ('aidomme_commitment_reports', 'aidomme_commitments', 'aidomme_offers') LOOP
      EXECUTE format('ALTER INDEX %I RENAME TO %I', item.indexname, replace(item.indexname, 'aidomme_', 'aidomme_legacy_'));
    END LOOP;
    ALTER TABLE aidomme_commitment_reports RENAME TO aidomme_legacy_commitment_reports;
    ALTER TABLE aidomme_commitments RENAME TO aidomme_legacy_commitments;
    ALTER TABLE aidomme_offers RENAME TO aidomme_legacy_offers;
  ELSE
    DROP TABLE aidomme_commitment_reports, aidomme_commitments, aidomme_offers;
  END IF;
  DROP TABLE aidomme_commitment_operations;
END
$legacy$;


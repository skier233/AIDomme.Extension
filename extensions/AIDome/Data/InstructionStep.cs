using System;

namespace AIDome2025.Data;

/// <summary>What kind of thing does this instruction step ask the user to do?</summary>
public enum InstructionKind
{
    /// <summary>Use a specific StimMethod for a timed duration.</summary>
    TimedMethod = 0,
    /// <summary>Edge N times using a specific method.</summary>
    EdgeCount = 1,
    /// <summary>Rest / hands-off pause.</summary>
    Rest = 2,
    /// <summary>Free-text domme instruction (e.g. "wash off").</summary>
    FreeText = 3,
    /// <summary>Finishing instruction (how to cum, if allowed).</summary>
    Finish = 4
}

/// <summary>
/// A single step in the session plan generated by the instruction engine.
/// Steps are ordered by <see cref="Ordinal"/> within a session.
/// </summary>
public sealed class InstructionStep
{
    public int Id { get; set; }

    public int SessionId { get; set; }
    public SessionRecord? Session { get; set; }

    /// <summary>Order within the session (0-based).</summary>
    public int Ordinal { get; set; }

    public InstructionKind Kind { get; set; }

    /// <summary>Optional FK to the stim method to use for this step.</summary>
    public int? StimMethodId { get; set; }
    public StimMethod? StimMethod { get; set; }

    /// <summary>Speed on 1-10 scale (if applicable).</summary>
    public int Speed { get; set; }

    /// <summary>Tenseness on 1-10 scale (if applicable).</summary>
    public int Tenseness { get; set; }

    /// <summary>Duration in seconds for timed steps, or edge count for EdgeCount steps.</summary>
    public int DurationOrCount { get; set; }

    /// <summary>Seconds to hold at the edge (for EdgeCount steps). 0 = no hold.</summary>
    public int HoldSeconds { get; set; }

    /// <summary>Human-readable instruction text shown to the user.</summary>
    public string Text { get; set; } = string.Empty;

    /// <summary>When the user started this step (null = not started yet).</summary>
    public DateTime? StartedAtUtc { get; set; }

    /// <summary>When the user completed this step (null = not completed).</summary>
    public DateTime? CompletedAtUtc { get; set; }
}
